export function localizeService(service: Service, lang: Lang): Service {
  if (lang !== 'be') return service;
  const tr = BE[service.id];
  if (!tr) return service;
  return {
    ...service,
    title: tr.title,
    summary: tr.summary,
    who: tr.who,
    amount: tr.amount,
    deadline: tr.deadline,
    checklist: service.checklist.map((row, i) => {
      const pair = tr.checklist[i];
      return pair ? { item: pair[0], where: pair[1] } : row;
    }),
    sources: service.sources.map((src) => ({
      ...src,
      title: tr.sourceTitle,
      point: src.point ? tr.sourcePoint : src.point,
    })),
  };
}
