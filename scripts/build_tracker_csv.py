def status_for(prefix: str) -> tuple[str, str]:
    raw = (RAW / f"{prefix}.md").exists()
    curated = (CURATED / f"{prefix}.json").exists()
    chunks = 0
    if curated:
        try:
            chunks = len(json.loads((CURATED / f"{prefix}.json").read_text(encoding="utf-8"))["chunks"])
        except (json.JSONDecodeError, KeyError):
            chunks = 0
    if curated:
        return "разобран", f"{chunks} чанков"
    if raw:
        return "скачан", "оригинал в raw/, разбор не сделан"
    return "не скачан", ""


def main() -> None:
    rows: list[list[str]] = []
    for index, (prefix, title, kind, number, date, edition, url, note) in enumerate(KNOWN, start=1):
        status, detail = status_for(prefix)
        comment = f"{note}. {detail}".strip(". ")
        rows.append([str(index), title, kind, number, date, edition, url, "@jaraslaukunin", status, comment])

    for offset, (title, kind, number, date, url, note) in enumerate(CANDIDATES, start=1):
        rows.append([
            str(len(KNOWN) + offset), title, kind, number, date, "уточнить",
            url, "", "не скачан", f"{note}. Реквизиты/ссылку уточнить на pravo.by перед скачиванием.",
        ])

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(HEADER)
        writer.writerows(rows)

    print(f"записано: {OUT.relative_to(REPO)} — {len(rows)} строк")
    print("импорт: Google Sheets → Файл → Импорт → CSV, UTF-8")
    print()
    for row in rows[: len(KNOWN)]:
        print(f"  {row[0]:>2}. [{row[8]}] {row[1][:60]}")


if __name__ == "__main__":
    main()