def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()

    settings = get_settings()
    docs, _ = load_curated(settings.corpus_dir)
    known = {chunk.chunk_id for chunk in collect_chunks(docs)}

    problems: list[str] = []
    for service in SERVICES:
        for source in service.sources:
            if source.point and source.point not in known:
                problems.append(f"{service.id}: источник не найден в корпусе — {source.point}")

    print(f"услуг: {len(SERVICES)}; чанков в корпусе: {len(known)}")
    for service in SERVICES:
        print(f"  {service.id:22} источников {len(service.sources)}, документов {len(service.checklist)}")
        print(f"      {service.amount[:88]}")
    if problems:
        print("\nОШИБКИ:")
        for problem in problems:
            print("  ", problem)
        sys.exit(1)

    if args.write:
        payload = [s.model_dump(mode="json") for s in SERVICES]
        settings.services_file.write_text(
            json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        print(f"\nзаписано: {settings.services_file}")
    else:
        print("\n(dry-run: добавьте --write)")


if __name__ == "__main__":
    main()
